"""Render the thin caller workflow for the verify pipeline."""
from __future__ import annotations

import hashlib
import json
import re

HEADER_TAG = "# Generated by anything-pipeline (ap init)."
HASH_PREFIX = "# ap-sha256: "

GATE_SCRIPT = """\
set -euo pipefail
echo "$NEEDS" | jq -r 'to_entries[] | "\\(.key): \\(.value.result)"'
if echo "$NEEDS" | jq -e 'all(.[]; .result == "success" or .result == "skipped")' >/dev/null; then
  echo "All verify jobs passed."
else
  echo "::error::At least one verify job failed or was cancelled."
  exit 1
fi
"""


def q(value) -> str:
    """A YAML scalar: JSON strings and literals are valid YAML and always safely quoted."""
    return json.dumps(value)


def job_ids(paths: list[str]) -> dict[str, str]:
    """Stable, unique, valid workflow job ids for unit paths."""
    ids: dict[str, str] = {}
    used: set[str] = set()
    for path in paths:
        base = "verify" if path == "." else "verify-" + re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")[:40]
        candidate, n = base.rstrip("-"), 2
        while candidate in used:
            candidate = f"{base.rstrip('-')}-{n}"
            n += 1
        used.add(candidate)
        ids[path] = candidate
    return ids


def render_verify(kit_repo: str, ref: str, ref_label: str, default_branch: str, units: list[dict]) -> str:
    """`units` items: {path, flavor, pm, inputs: {name: value}}. Returns the full file text."""
    ids = job_ids([u["path"] for u in units])
    uses = f"{kit_repo}/.github/workflows/verify.yml@{ref}"
    uses_line = f"    uses: {uses}" + (f" # {ref_label}" if ref_label else "")

    lines = [
        "name: verify",
        "",
        "on:",
        "  pull_request:",
        "  push:",
        f"    branches: [{q(default_branch)}]",
        "  merge_group:",
        "",
        "concurrency:",
        "  group: verify-${{ github.workflow }}-${{ github.ref }}",
        "  cancel-in-progress: ${{ github.event_name == 'pull_request' }}",
        "",
        "permissions: {}",
        "",
        "jobs:",
    ]
    for unit in units:
        lines += [
            f"  {ids[unit['path']]}:",
            f"    name: {q('verify' if unit['path'] == '.' else 'verify (' + unit['path'] + ')')}",
            "    permissions:",
            "      contents: read",
            uses_line,
            "    with:",
            f"      flavor: {q(unit['flavor'])}",
        ]
        if unit["pm"]:
            lines.append(f"      pm: {q(unit['pm'])}")
        lines.append(f"      working-directory: {q(unit['path'])}")
        for name, value in unit["inputs"].items():
            lines.append(f"      {name}: {q(value)}")
        lines.append("")

    needs = ", ".join(ids[u["path"]] for u in units)
    lines += [
        "  # The only check branch protection needs to require. Skipped jobs pass; failed or cancelled ones do not.",
        "  gate:",
        "    name: gate",
        "    if: ${{ always() }}",
        f"    needs: [{needs}]",
        "    runs-on: ubuntu-latest",
        "    timeout-minutes: 5",
        "    permissions: {}",
        "    steps:",
        "      - name: Require every verify job to pass",
        "        env:",
        "          NEEDS: ${{ toJSON(needs) }}",
        "        run: |",
    ]
    lines += [f"          {line}" if line else "" for line in GATE_SCRIPT.rstrip("\n").split("\n")]
    body = "\n".join(lines) + "\n"
    return with_header(body)


def with_header(body: str) -> str:
    digest = hashlib.sha256(body.encode()).hexdigest()
    return f"{HEADER_TAG}\n{HASH_PREFIX}{digest}\n{body}"


def generated_state(text: str) -> str:
    """'pristine' if generated and unmodified, 'modified' if generated then edited, else 'foreign'."""
    lines = text.split("\n", 2)
    if len(lines) < 3 or lines[0] != HEADER_TAG or not lines[1].startswith(HASH_PREFIX):
        return "foreign"
    recorded = lines[1][len(HASH_PREFIX):].strip()
    actual = hashlib.sha256(lines[2].encode()).hexdigest()
    return "pristine" if recorded == actual else "modified"
